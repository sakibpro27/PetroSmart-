"""
Run the automated test suite and write the actual results into the report,
so the Testing chapter only ever shows tests that really ran.

Run from the project folder (with the virtual environment active):

    python documentation/tools/generate_test_report.py

Writes documentation/academic/appendix-b-test-results.md
"""

import os
import sys
import time
import unittest
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)
sys.argv = ["manage.py", "test"]  # so settings use the fast test password hasher, as `manage.py test` does
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")

import django  # noqa: E402

django.setup()

from django.test.runner import DiscoverRunner  # noqa: E402

MODULE_TITLES = {
    "accounts": "Accounts, login security and user management",
    "core": "Login flow and overview page",
    "tenants": "Tenants, subscriptions and isolation",
    "station": "Outlet set-up",
    "sales": "Shift Cards: formulas, saving, corrections, reports",
    "stock": "Tank stock",
    "purchases": "Fuel purchases",
    "finance": "Credit, bills and expenses",
    "reports": "Dashboard, reports and exports",
    "operations": "Inventory, employees, reminders, audit log",
}


class RecordingResult(unittest.TextTestResult):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.outcomes = []

    def _record(self, test, outcome, detail=""):
        self.outcomes.append((test, outcome, detail))

    def addSuccess(self, test):
        super().addSuccess(test)
        self._record(test, "Pass")

    def addFailure(self, test, err):
        super().addFailure(test, err)
        self._record(test, "Fail", self._exc_info_to_string(err, test).splitlines()[-1])

    def addError(self, test, err):
        super().addError(test, err)
        self._record(test, "Error", self._exc_info_to_string(err, test).splitlines()[-1])

    def addSkip(self, test, reason):
        super().addSkip(test, reason)
        self._record(test, "Skipped", reason)

    def addSubTest(self, test, subtest, err):
        super().addSubTest(test, subtest, err)
        if err is not None:
            self._record(test, "Fail", str(subtest))


class Runner(DiscoverRunner):
    def get_resultclass(self):
        return RecordingResult

    def run_suite(self, suite, **kwargs):
        runner = unittest.TextTestRunner(verbosity=0, resultclass=RecordingResult, stream=open(os.devnull, "w"))
        self.result = runner.run(suite)
        return self.result


def describe(test):
    method = getattr(test, test._testMethodName)
    doc = (method.__doc__ or "").strip().split("\n")[0]
    if doc:
        return doc
    return test._testMethodName.removeprefix("test_").replace("_", " ").capitalize()


def main():
    started = time.time()
    runner = Runner(verbosity=0)
    runner.run_tests([])
    result = runner.result
    seconds = time.time() - started

    by_module = {}
    for test, outcome, detail in result.outcomes:
        module = type(test).__module__.split(".")[0]
        by_module.setdefault(module, []).append((test, outcome, detail))

    passed = sum(1 for _, o, _ in result.outcomes if o == "Pass")
    failed = len(result.outcomes) - passed
    lines = [
        "# Appendix B: Automated test results",
        "",
        f"*Generated by `documentation/tools/generate_test_report.py` on {datetime.now():%d %B %Y at %H:%M}.*",
        "",
        f"- Tests run: **{len(result.outcomes)}**",
        f"- Passed: **{passed}**",
        f"- Failed or errors: **{failed}**",
        f"- Time taken: {seconds:.0f} seconds",
        f"- Command: `python manage.py test` (Django test runner, temporary SQLite test database)",
        "",
        "Each row is one automated test case. *Expected result* is what the test asserts; *actual result* "
        "is the outcome of this run.",
        "",
    ]
    number = 0
    for module in sorted(by_module, key=lambda m: list(MODULE_TITLES).index(m) if m in MODULE_TITLES else 99):
        rows = by_module[module]
        lines += [f"## {MODULE_TITLES.get(module, module)} (`{module}`): {len(rows)} tests", "",
                  "| ID | Test class | Test case (expected behaviour) | Actual result |", "|---|---|---|---|"]
        for test, outcome, detail in sorted(rows, key=lambda r: (type(r[0]).__name__, r[0]._testMethodName)):
            number += 1
            note = f" ({detail})" if detail else ""
            lines.append(f"| T{number:03d} | {type(test).__name__} | {describe(test)} | {outcome}{note} |")
        lines.append("")

    out = ROOT / "documentation" / "academic" / "appendix-b-test-results.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(result.outcomes)} tests, {passed} passed, {failed} not passed. Written to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
